
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    location VARCHAR(100),
    university VARCHAR(200),
    profile_picture BYTEA,
    profile_picture_content_type VARCHAR(50)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    location VARCHAR(200) NOT NULL,
    category VARCHAR(80) NOT NULL,
    start_date_time TIMESTAMP NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    attendee_count INTEGER NOT NULL DEFAULT 0 CHECK (attendee_count >= 0),
    organizer_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX idx_events_start_date_time
    ON events(start_date_time);

CREATE TABLE event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    event_id BIGINT NOT NULL REFERENCES events(id),
    status VARCHAR(20) NOT NULL,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_registration_user_event UNIQUE (user_id, event_id)
);

CREATE INDEX idx_event_registrations_event_id
    ON event_registrations(event_id);
